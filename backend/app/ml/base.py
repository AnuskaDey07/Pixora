"""Frozen ML interface.

Every ML function returns an MLResult. No exceptions.

Rules:
- No file I/O inside ML functions.
- No DB access, no Flask, no Celery, no HTTP from ML code.
- Models load once at worker startup (Model.load), never per call.
- Every function documents its params and meta dicts.

Do not edit this file without agreement from both owners.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from PIL import Image


@dataclass
class MLResult:
    """Standard return value for every ML function."""

    ok: bool
    output: Image.Image | dict | None = None
    meta: dict[str, Any] = field(default_factory=dict)
    error: str | None = None


class Model:
    """Base class for stateful models.

    Subclass and override load() and run(). Models should be instantiated
    once per worker process, and load() called once at startup.
    """

    name: str = "unnamed"

    def load(self) -> None:
        """Load weights into memory. Called once at worker startup."""
        raise NotImplementedError

    def run(self, image: Image.Image, params: dict) -> MLResult:
        """Run inference. Returns MLResult. Never raises."""
        raise NotImplementedError
