"""Generate strong secrets for a production .env.

Usage:
    python scripts/generate_secrets.py > .env.prod

Each run produces fresh values. Save the output to .env.prod and never commit it.
"""
from __future__ import annotations

import secrets
import string
import sys


def rand_hex(n_bytes: int = 32) -> str:
    return secrets.token_hex(n_bytes)


def rand_password(length: int = 32) -> str:
    alphabet = string.ascii_letters + string.digits + "!@#$%^&*()-_=+"
    return "".join(secrets.choice(alphabet) for _ in range(length))


def main() -> int:
    pg_user = "pixora"
    pg_pw = rand_password(28)
    pg_db = "pixora"

    print("# ─────────────────────────────────────────────────────────────")
    print("# Pixora — production environment")
    print("# Auto-generated by scripts/generate_secrets.py")
    print("# DO NOT COMMIT. Keep this file on the deployment host only.")
    print("# ─────────────────────────────────────────────────────────────")
    print()
    print("# --- Flask ---")
    print("FLASK_ENV=production")
    print(f"SECRET_KEY={rand_hex(32)}")
    print(f"JWT_SECRET_KEY={rand_hex(32)}")
    print("JWT_ACCESS_TOKEN_EXPIRES_MINUTES=30")
    print("JWT_REFRESH_TOKEN_EXPIRES_DAYS=14")
    print("API_HOST_PORT=5000")
    print()
    print("# --- Postgres ---")
    print(f"POSTGRES_USER={pg_user}")
    print(f"POSTGRES_PASSWORD={pg_pw}")
    print(f"POSTGRES_DB={pg_db}")
    print("POSTGRES_HOST_PORT=5432")
    print(f"DATABASE_URL=postgresql+psycopg://{pg_user}:{pg_pw}@postgres:5432/{pg_db}")
    print()
    print("# --- Redis / Celery ---")
    print("REDIS_URL=redis://redis:6379/0")
    print("CELERY_BROKER_URL=redis://redis:6379/1")
    print("CELERY_RESULT_BACKEND=redis://redis:6379/2")
    print()
    print("# --- MinIO ---")
    print("MINIO_ENDPOINT=minio:9000")
    print("# Set this to your public domain once you have one, e.g. pixora.example.com")
    print("MINIO_PUBLIC_ENDPOINT=localhost:9000")
    print("MINIO_ROOT_USER=pixora")
    print(f"MINIO_ROOT_PASSWORD={rand_password(28)}")
    print("MINIO_USE_SSL=false")
    print("MINIO_API_PORT=9000")
    print("MINIO_CONSOLE_PORT=9001")
    print("S3_BUCKET_UPLOADS=pixora-uploads")
    print("S3_BUCKET_THUMBS=pixora-thumbs")
    print("S3_BUCKET_RESULTS=pixora-results")
    print("S3_BUCKET_MASKS=pixora-masks")
    print()
    print("# --- Nginx ---")
    print("NGINX_HTTP_PORT=80")
    print()
    print("# --- Uploads ---")
    print("MAX_CONTENT_LENGTH_MB=50")
    print("ALLOWED_IMAGE_MIMES=image/png,image/jpeg,image/webp")
    print()
    print("# --- ML ---")
    print("ML_STUB_MODE=true")
    return 0


if __name__ == "__main__":
    sys.exit(main())
